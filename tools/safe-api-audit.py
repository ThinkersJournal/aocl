#!/usr/bin/env python3
"""ENUMERATE every `pub fn` (and every method of a `pub trait`) of the safe wrapper crates and classify its arguments: the denominator
of the safe-API memory-safety audit.

Enumeration: `git ls-files crates/<wrapper>/src` (the index, never a disk walk), then a comment-stripped regex pass over
`pub [unsafe] fn NAME<..>(PARAMS) -> RET { BODY }` and over the `fn`s declared inside `pub trait X { .. }` (balanced parentheses and
braces). A sealed trait stops IMPLEMENTING, not CALLING, so its methods are public safe API too. Known blind spots, each checked
separately: `pub fn` generated by a macro (checked: no `macro_rules!` body in the wrapper crates contains `pub fn`; cross-checked
against `cargo doc` HTML: the free-function counts of rustdoc and of this pass agree except where noted in the audit doc), methods of
`impl Trait for` blocks (the trait declaration is counted instead), `pub(crate)` items (not public).

Per function: the arguments that carry a length, index, stride, offset, pointer or handle (slice `&[..]`/`&mut [..]`, `Vec`, raw
pointer, size-like scalars named n/m/k/ld*/inc*/stride/offset/nnz/len/...), and a HEURISTIC `validated`: the body text BEFORE its first
`unsafe` contains `.len()`, `InvalidArgument`, or a call to a `check_*`/`validate*`/`require*`/`ensure*` helper. The heuristic only
says a check is PRESENT; whether it is CORRECT and COMPLETE is the manual verdict column and the guard-page harness.

    python tools/safe-api-audit.py [--csv docs/safe-api-audit/table.csv]
`parse(text, filename)` is importable (tools/safe-api-versions.py runs it over every published .crate).
"""
import csv
import re
import subprocess
import sys

WRAPPERS = ["blas", "lapack", "fft", "math", "sparse", "rng", "securerng", "utils", "compression", "crypto",
            "data-analytics", "scalapack", "openrng"]
SIZE_NAMES = re.compile(r"^(n|m|k|nnz|len|length|size|count|dim|dimen|nrows|ncols|rows|cols|lda|ldb|ldc|ldz|ldu|ldvt|ldvl|ldvr|ldx|ldy|lwork|"
                        r"incx|incy|inc|stride|offset|nrhs|n_rhs|ntrial|nstreams|nskip|kl|ku|kd|nb|ia|ja|ib|jb|ic|jc|order_len|dim[a-z0-9_]*|"
                        r"index|idx|i|j|row|col|rowptr|colind|indx|ldw|batch|batch_count|group_count|nbatch)$")
FN = re.compile(r"\bpub\s+(unsafe\s+)?(?:const\s+)?fn\s+(\w+)")
TRAIT = re.compile(r"\bpub\s+trait\s+(\w+)[^{]*\{")
CHECK = re.compile(r"\.len\(\)|InvalidArgument|\bcheck_\w+\(|\bvalidate\w*\(|\brequire\w*\(|\bensure\w*\(")
NL = chr(10)


def strip_comments(s):
    out, i, n = [], 0, len(s)
    while i < n:
        if s.startswith("//", i):
            while i < n and s[i] != NL:
                i += 1
        elif s.startswith("/*", i):
            j = s.find("*/", i + 2)
            j = n if j < 0 else j + 2
            out.append(NL * s.count(NL, i, j))
            i = j
        elif s[i] == '"':
            j = i + 1
            while j < n and s[j] != '"':
                j += 2 if s[j] == "\\" else 1
            out.append('""' + NL * s.count(NL, i, j))
            i = j + 1
        else:
            out.append(s[i])
            i += 1
    return "".join(out)


def balanced(s, i, open_c, close_c):
    depth, j = 0, i
    while j < len(s):
        c = s[j]
        if c == open_c:
            depth += 1
        elif c == close_c:
            depth -= 1
            if depth == 0:
                return j
        j += 1
    return -1


def split_params(p):
    out, depth, cur = [], 0, ""
    for c in p:
        if c in "<([{":
            depth += 1
        elif c in ">)]}":
            depth -= 1
        if c == "," and depth == 0:
            out.append(cur.strip())
            cur = ""
        else:
            cur += c
    if cur.strip():
        out.append(cur.strip())
    return out


def classify(params):
    slices, ptrs, sizes, handles = [], [], [], []
    for p in params:
        if p in ("self", "&self", "&mut self", "mut self"):
            continue
        name, _, ty = p.partition(":")
        name, ty = name.strip().lstrip("mut ").strip(), ty.strip()
        if re.match(r"&\s*(mut\s+)?\[", ty) or ty.startswith("Vec<") or re.match(r"&\s*(mut\s+)?Vec<", ty):
            slices.append(name)
        elif "*const" in ty or "*mut" in ty:
            ptrs.append(name)
        elif SIZE_NAMES.match(name) and re.match(r"(usize|u?i(32|64|size)|u(32|64))$", ty):
            sizes.append(name)
        elif re.match(r"&\s*(mut\s+)?[A-Z]\w*(<.*>)?$", ty) and "str" not in ty:
            handles.append(name)
    return slices, ptrs, sizes, handles


def parse(text, f):
    """-> list of dicts, one per `pub [unsafe] fn` and per `pub trait` method in the source text (file name `f`, for the record)."""
    src = strip_comments(text.replace(chr(13) + NL, NL))
    rows = []
    for m in FN.finditer(src):
        unsafe = bool(m.group(1))
        j = m.end()
        if src[j:j + 1] == "<":
            j = balanced(src, j, "<", ">") + 1
            if j <= 0:
                continue
        k = src.find("(", j)
        if k < 0:
            continue
        e = balanced(src, k, "(", ")")
        params = split_params(src[k + 1:e])
        b = src.find("{", e)
        semi = src.find(";", e)
        body = ""
        if b >= 0 and (semi < 0 or b < semi):
            body = src[b:balanced(src, b, "{", "}") + 1]
        sl, pt, sz, hd = classify(params)
        rows.append({"file": f, "line": src.count(NL, 0, m.start()) + 1, "fn": m.group(2), "unsafe": unsafe, "slices": sl, "ptrs": pt,
                     "sizes": sz, "handles": hd, "in_scope": (not unsafe) and bool(sl or pt or sz), "validated": bool(CHECK.search(body.split("unsafe", 1)[0])),
                     "trait_method": False})
    for tm in TRAIT.finditer(src):
        te = balanced(src, tm.end() - 1, "{", "}")
        tb = src[tm.end():te]
        for fm in re.finditer(r"\b(unsafe\s+)?fn\s+(\w+)", tb):
            unsafe = bool(fm.group(1))
            k = tb.find("(", fm.end())
            e = balanced(tb, k, "(", ")")
            sl, pt, sz, hd = classify(split_params(tb[k + 1:e]))
            rows.append({"file": f, "line": src.count(NL, 0, tm.end() + fm.start()) + 1, "fn": tm.group(1) + "::" + fm.group(2), "unsafe": unsafe,
                         "slices": sl, "ptrs": pt, "sizes": sz, "handles": hd, "in_scope": (not unsafe) and bool(sl or pt or sz),
                         "validated": False, "trait_method": True})
    return rows


ANYFN = re.compile(r"(?<!\w)fn\s+(\w+)")
CALL = re.compile(r"(?<!\w)(?:T|Self|S|F)::(\w+)\(")


def defs_index(texts):
    """name -> list of (head_has_check, callee_names) for EVERY fn with a body in the given sources (incl. non-pub and macro bodies)."""
    idx = {}
    for t in texts:
        src = strip_comments(t.replace(chr(13) + NL, NL))
        for m in ANYFN.finditer(src):
            j = m.end()
            if src[j:j + 1] == "<":
                j = balanced(src, j, "<", ">") + 1
                if j <= 0:
                    continue
            k = src.find("(", j)
            if k < 0:
                continue
            e = balanced(src, k, "(", ")")
            b = src.find("{", e)
            semi = src.find(";", e)
            if b < 0 or (0 <= semi < b):
                continue
            body = src[b:balanced(src, b, "{", "}") + 1]
            head = body.split("unsafe", 1)[0]
            idx.setdefault(m.group(1), []).append((bool(CHECK.search(head)), sorted(set(CALL.findall(body)))))
    return idx


def deep_validated(name, idx, depth=3, seen=None):
    """A check is PRESENT on some path: in a definition of `name`, or in the (T::/Self::) callees of its definitions, to `depth`."""
    seen = seen or set()
    if name in seen or depth < 0:
        return False
    seen.add(name)
    for has, callees in idx.get(name, []):
        if has or any(deep_validated(c, idx, depth - 1, seen) for c in callees):
            return True
    return False


def main():
    csv_path = sys.argv[sys.argv.index("--csv") + 1] if "--csv" in sys.argv else None
    rows, summary = [], {}
    for w in WRAPPERS:
        files = subprocess.run(["git", "ls-files", f"crates/aocl-{w}/src"], capture_output=True, text=True, check=True).stdout.split()
        files = [f for f in files if f.endswith(".rs")]
        tot = safe = uns = scope = auto = tr = 0
        texts = {f: open(f, encoding="utf8", errors="replace").read() for f in files}
        idx = defs_index(texts.values())
        for f in files:
            for r in parse(texts[f], f):
                short = r["fn"].split("::")[-1]
                r["deep"] = deep_validated(short, idx)
                trait = r["trait_method"]
                tot += 1
                uns += r["unsafe"]
                safe += not r["unsafe"]
                tr += trait
                if r["in_scope"]:
                    scope += 1
                    auto += r["deep"]
                verdict = "n/a"
                if r["in_scope"]:
                    verdict = ("READ (trait method; check on an impl path)" if r["deep"] else "REVIEW (trait method; no check on any impl path)") if trait else ("checks present: read pending" if r["deep"] else "REVIEW")
                rows.append({"crate": f"aocl-{w}", "file": r["file"], "line": r["line"], "fn": r["fn"], "kind": "unsafe" if r["unsafe"] else "safe",
                             "trait_method": "yes" if trait else "", "slice_args": " ".join(r["slices"]), "ptr_args": " ".join(r["ptrs"]),
                             "size_args": " ".join(r["sizes"]), "handle_args": " ".join(r["handles"]), "in_scope": "yes" if r["in_scope"] else "no",
                             "check_before_ffi_heuristic": ("on an impl path" if r["deep"] else "NO") if trait else ("direct" if r["validated"] else ("via callee" if r["deep"] else "NO")),
                             "guard_page_test": "", "verdict": verdict})
        summary[w] = (tot, safe, uns, tr, scope, auto)
    print("enumeration: git ls-files crates/aocl-<wrapper>/src + comment-stripped regex over `pub [unsafe] fn` and `pub trait` methods (balanced parens/braces)")
    hdr = ("pub fn+trait fn", "safe", "unsafe", "of which trait", "in scope", "check on a path")
    print(f"{'wrapper':22}" + "".join(f"{h:>16}" for h in hdr))
    T = [0] * 6
    for w, v in summary.items():
        print(f"aocl-{w:17}" + "".join(f"{x:>16}" for x in v))
        T = [a + b for a, b in zip(T, v)]
    print(f"{'TOTAL':22}" + "".join(f"{x:>16}" for x in T))
    print("in scope = SAFE fn with >= 1 slice / Vec / raw-pointer / size-like scalar argument; 'check present' = heuristic only (a check exists, not that it is right)")
    if csv_path:
        with open(csv_path, "w", newline="", encoding="utf8") as fh:
            wr = csv.DictWriter(fh, fieldnames=list(rows[0]))
            wr.writeheader()
            wr.writerows(rows)
        print(f"wrote {len(rows)} rows to {csv_path}")


if __name__ == "__main__":
    main()
