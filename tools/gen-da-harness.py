#!/usr/bin/env python3
"""Generate crates/aocl-data-analytics/tests/<name>.rs: a guard-page harness for the free statistics functions of aocl-data-analytics
(`mean`, `variance`, `geometric_mean`, `harmonic_mean`, `skewness`, `kurtosis`, `moment`, `quantile`, `five_point_summary`,
`covariance_matrix`, `correlation_matrix`; f64 and f32). Method as tools/gen-blas-harness.py: a CONTROL call with the contractual sizes
must succeed, then one case per slice argument with that slice one element short at the end of a committed page before a
PAGE_NOACCESS page (a fault = HOLE). Row-major tight matrices, M = 3 rows, N = 4 columns; the output size depends on the axis
(`Col` -> n_cols, `Row` -> n_rows, `All` -> 1). The data is positive and varied (the means and moments need it).
    python tools/gen-da-harness.py [--assert] [--only NAME] > crates/aocl-data-analytics/tests/stats_lengths.rs
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from harness_trim import trim  # noqa: E402

NL = chr(10)
AXES = [("col", "Axis::Col", "N"), ("row", "Axis::Row", "M"), ("all", "Axis::All", "1")]
RULES = []


def rule(name, slices, call, per_axis=True):
    RULES.append((name, slices, call, per_axis))


# slices: (arg, size expr with {o} = the axis output size, mutable)
def outs(*names):
    return [(n, "{o}", 1) for n in names]


rule("mean", [("x", "M*N", 0)] + outs("out"), "mean::<T>({ax}, M, N, {x}, {out})")
rule("variance", [("x", "M*N", 0)] + outs("mean_out", "variance_out"), "variance::<T>({ax}, M, N, {x}, 1, {mean_out}, {variance_out})")
rule("geometric_mean", [("x", "M*N", 0)] + outs("out"), "geometric_mean::<T>({ax}, M, N, {x}, {out})")
rule("harmonic_mean", [("x", "M*N", 0)] + outs("out"), "harmonic_mean::<T>({ax}, M, N, {x}, {out})")
rule("skewness", [("x", "M*N", 0)] + outs("mean_out", "variance_out", "skew_out"), "skewness::<T>({ax}, M, N, {x}, {mean_out}, {variance_out}, {skew_out})")
rule("kurtosis", [("x", "M*N", 0)] + outs("mean_out", "variance_out", "kurtosis_out"), "kurtosis::<T>({ax}, M, N, {x}, {mean_out}, {variance_out}, {kurtosis_out})")
rule("moment", [("x", "M*N", 0)] + outs("mean_out", "moment_out"), "moment::<T>({ax}, M, N, {x}, 2, false, {mean_out}, {moment_out})")
rule("quantile", [("x", "M*N", 0)] + outs("quantile_out"), "quantile::<T>({ax}, M, N, {x}, HALF, {quantile_out}, QuantileType::Type1)")
rule("five_point_summary", [("x", "M*N", 0)] + outs("min", "lower", "median", "upper", "max"),
     "five_point_summary::<T>({ax}, M, N, {x}, {min}, {lower}, {median}, {upper}, {max})")
rule("covariance_matrix", [("x", "M*N", 0), ("cov", "N*N", 1)], "covariance_matrix::<T>(M, N, {x}, 1, {cov})", per_axis=False)
rule("correlation_matrix", [("x", "M*N", 0), ("corr", "N*N", 1)], "correlation_matrix::<T>(M, N, {x}, {corr})", per_axis=False)

# kernels / distances: x is M x K, y is N x K (Some), d is M x N, row-major tight (ldx = ldy = K, ldd = N)
KRULES = [
    ("linear_kernel", "linear_kernel::<T>(M, N, K, {x}, Some({y}), {d})"),
    ("rbf_kernel", "rbf_kernel::<T>(M, N, K, {x}, Some({y}), {d}, HALF)"),
    ("polynomial_kernel", "polynomial_kernel::<T>(M, N, K, {x}, Some({y}), {d}, HALF, 2, HALF)"),
    ("sigmoid_kernel", "sigmoid_kernel::<T>(M, N, K, {x}, Some({y}), {d}, HALF, HALF)"),
    ("pairwise_distances", "pairwise_distances::<T>(M, N, K, {x}, Some({y}), {d}, TWO, Metric::Euclidean)"),
]
for _n, _c in KRULES:
    rule(_n, [("x", "M*K", 0), ("y", "N*K", 0), ("d", "M*N", 1)], _c, per_axis=False)

KIND = {"f64": ("f64", "1.0", "0.5", "(1.0 + (i % 5) as f64)", "0.0"), "f32": ("f32", "1.0f32", "0.5f32", "(1.0 + (i % 5) as f32)", "0.0f32")}


def main():
    only = sys.argv[sys.argv.index("--only") + 1] if "--only" in sys.argv else None
    bases = set(sys.argv[sys.argv.index("--bases") + 1].split(",")) if "--bases" in sys.argv else None
    assert_mode = "--assert" in sys.argv
    out = []
    w = out.append
    w("//! GENERATED by tools/gen-da-harness.py (do not edit): guard-page harness for the free statistics functions of aocl-data-analytics.")
    w("#![cfg(windows)]")
    w('#![allow(unused_parens, reason = "generated size expressions are parenthesised")]')
    w("use aocl_data_analytics::*;")
    w("use core::ffi::c_void;")
    w("""extern "system" {
    fn VirtualAlloc(addr: *mut c_void, size: usize, ty: u32, prot: u32) -> *mut c_void;
    fn VirtualProtect(addr: *mut c_void, size: usize, prot: u32, old: *mut u32) -> i32;
    fn VirtualFree(addr: *mut c_void, size: usize, ty: u32) -> i32;
}
const PAGE: usize = 4096;
const M: usize = 3;
const N: usize = 4;
const K: usize = 5;
fn at_guard<T: Copy, X>(n: usize, init: impl Fn(usize) -> T, f: impl FnOnce(&mut [T]) -> X) -> X {
    assert!(n * core::mem::size_of::<T>() <= PAGE);
    unsafe {
        let base = VirtualAlloc(core::ptr::null_mut(), 2 * PAGE, 0x3000, 0x04);
        assert!(!base.is_null());
        let mut old = 0u32;
        assert_ne!(VirtualProtect((base as *mut u8).add(PAGE) as *mut c_void, PAGE, 0x01, &mut old), 0);
        let start = (base as *mut u8).add(PAGE - n * core::mem::size_of::<T>()) as *mut T;
        for i in 0..n {
            start.add(i).write(init(i));
        }
        let r = f(core::slice::from_raw_parts_mut(start, n));
        VirtualFree(base, 0, 0x8000);
        r
    }
}
fn report<T: core::fmt::Debug>(name: &str, r: core::result::Result<T, aocl_error::Error>) {
    println!("RESULT {name} {}", if r.is_err() { "refused" } else { "accepted" });
}
""")
    count = 0
    for name, slices, call, per_axis in RULES:
        if only and name != only:
            continue
        if bases is not None and name not in bases:
            continue
        for kind, (t, one, half, init, zero) in KIND.items():
            for label, ax, o in (AXES if per_axis else [("", "", "1")]):
                tag = f"{name}_{kind}" + (f"_{label}" if label else "")
                sizes = {a: "(" + s.replace("{o}", o) + ")" for a, s, _ in slices}

                def initexpr(a):
                    return f"|i| {init}" if a in ("x", "y") else f"|_| {zero}"

                def call_with(short):
                    c = call.replace("::<T>", f"::<{t}>").replace("{ax}", ax).replace("HALF", half).replace("TWO", "2.0" if t == "f64" else "2.0f32")
                    for a, _, mut in slices:
                        c = c.replace("{" + a + "}", (a if mut else "&*" + a) if a == short else ("&mut " if mut else "&") + "v_" + a)
                    return c

                def lets(skip):
                    return "".join(f"let {'mut ' if m else ''}v_{a}: Vec<{t}> = (0..{sizes[a]}).map({initexpr(a)}).collect(); " for a, _, m in slices if a != skip)

                ctl = (f'assert!(r.is_ok(), "{tag}_control: {{:?}}", r.as_ref().err());' if assert_mode else f'report("{tag}_control", r.map(|_| ()));')
                w("#[test]" + NL + f"fn {tag}_control() {{ {lets(None)}let r = {call_with(None)}; {ctl} }}")
                for a, _, _ in slices:
                    tail = (f'assert!(r.is_err(), "{tag}_short_{a}: a buffer one element short must be refused before the FFI call");' if assert_mode
                            else f'report("{tag}_short_{a}", r.map(|_| ()));')
                    w("#[test]" + NL + f"fn {tag}_short_{a}() {{ {lets(a)}let r = at_guard::<{t}, _>({sizes[a]} - 1, {initexpr(a)}, |{a}| {call_with(a)}); {tail} }}")
                    count += 1
    print(trim(NL.join(out)))
    print(f"// {count} short cases", file=sys.stderr)


if __name__ == "__main__":
    main()
